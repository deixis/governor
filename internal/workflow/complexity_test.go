package workflow

import (
	"os"
	"path/filepath"
	"testing"

	"github.com/deixis/governor/internal/report"
)

func TestDropGenerated(t *testing.T) {
	dir := t.TempDir()
	if err := os.WriteFile(filepath.Join(dir, "a.go"), []byte("package a\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(dir, "a.pb.go"), []byte("// Code generated by protoc-gen-go. DO NOT EDIT.\n\npackage a\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	e := &Engine{Workspace: dir}
	entries := []report.ComplexityEntry{
		{File: "a.go", Function: "Hand", Complexity: 3},
		{File: "a.pb.go", Function: "Unmarshal", Complexity: 40},
		{File: filepath.Join(dir, "a.pb.go"), Function: "Marshal", Complexity: 30},
	}
	got := e.dropGenerated(entries)
	if len(got) != 1 || got[0].Function != "Hand" {
		t.Errorf("dropGenerated = %+v, want only Hand", got)
	}
}
